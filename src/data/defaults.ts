const CURRENT_DATE = "2026-09-30";
const CURRENT_DOT = "2026-09";

type Seed = {
  id: string;
  zoneId: string;
  group: string;
  name: string;
  shortLabel: string;
  detail?: string;
  kind?: ServiceItem["kind"];
  intervalMiles?: number | null;
  intervalMonths?: number | null;
  askOnFirstVisit?: boolean;
};

/**
 * Jobs where the scheduled work is a look, a measurement, or a lube. Nothing is thrown away, so the
 * diagram warns in white. Everything not listed here puts a new part or a fresh fluid in, which
 * warns in red.
 */
export const inspectionIds = new Set([
  // Tires and alignment: moving and adjusting what is already on the car.
  "tire-rotation",
  "alignment",
  // Brakes: the pads, rotors, and hydraulics get measured and cleaned on this schedule.
  "pads-front",
  "pads-rear",
  "rotors-front",
  "rotors-rear",
  "slides-front",
  "slides-rear",
  "parking-brake",
  "master",
  // Engine: gaskets and seals watched for leaks rather than swapped on a clock.
  "tpi-gaskets",
  "valve-cover",
  // Cooling: the fan, pump, and heater core are checked and replaced only when they fail.
  "fan",
  "water-pump",
  "heater-core",
  // Fuel: a pressure reading, not a part.
  "regulator",
  // Exhaust: bolts, gaskets, and hangers checked for leaks and rust.
  "headers",
  "axle-back",
  // Transmission: adjustment and behavior checks that keep a 700R4 alive.
  "tv-cable",
  "lockup",
  "cooler-lines",
  // Rear axle: play, noise, and seepage checks.
  "ujoints",
  "rear-bearings",
  "pinion",
  // Steering and suspension: all of it is checked for play, tears, and leaks.
  "rack",
  "tie-rods",
  "ball-joints",
  "leaf-front",
  "leaf-rear",
  "bushings-front",
  "bushings-rear",
  "sway-front",
  "sway-rear",
  "front-bearings",
  // Electrical and body: output, operation, and lube checks.
  "alternator",
  "headlight-left",
  "headlight-right",
  "headlight-lube",
  "top",
  "ac",
  "cluster",
]);

function workFor(id: string): ItemWork {
  return inspectionIds.has(id) ? "inspect" : "replace";
}

function item(seed: Seed): ServiceItem {
  const kind = seed.kind ?? "service";
  return {
    id: seed.id,
    zoneId: seed.zoneId,
    group: seed.group,
    name: seed.name,
    shortLabel: seed.shortLabel,
    detail: seed.detail,
    kind,
    work: workFor(seed.id),
    intervalMiles: seed.intervalMiles ?? null,
    intervalMonths: seed.intervalMonths ?? null,
    lastDate: kind === "problem-only" ? null : CURRENT_DATE,
    lastMiles: null,
    stillOriginal: false,
    askOnFirstVisit: seed.askOnFirstVisit ?? false,
    tread32: null,
    dotDate: kind === "tire" ? CURRENT_DOT : null,
    thicknessMm: null,
  };
}

